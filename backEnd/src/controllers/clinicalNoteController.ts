/**
 * Patient clinical notes (Patient File). Mounted under /api/patients/:id/clinical-notes.
 *
 * Access = the EXISTING rules, unchanged: every route is authenticated and clinic-scoped (`protect`); reading is open to any
 * role of the clinic (same as the patient file itself); creating / editing needs an active plan + owner|doctor (the same
 * "clinical write" rule the dental routes use). The full role redesign is a later phase.
 *
 * Nothing about scoping is taken from the client: clinicId comes from the authenticated user, the patient is re-loaded
 * with that clinicId, and any source record (visit / treatment) must belong to the SAME clinic AND patient.
 */
const idParam = (v: unknown) => (typeof v === "string" && mongoose.isValidObjectId(v) ? v : null);

export const loadNotePatient = async (req: Request, res: Response) => {
  const pid = idParam(req.params.id);
  const patient = pid ? await Patient.findOne({ _id: pid, clinicId: req.clinicId }).select("_id") : null;
  if (!patient) {
    // identical answer for "no such patient" and "another clinic's patient" — no tenant probing
    res.status(404).json({ message: "Patient not found" });
    return null;
  }
  return patient;
};

export const who = (u: unknown): { _id: string; name: string } | null => {
  const x = u as { _id?: unknown; name?: string } | null | undefined;
  return x && x._id && typeof x.name === "string" ? { _id: String(x._id), name: x.name } : null;
};

interface NoteDoc {
  _id: Types.ObjectId;
  patientId: Types.ObjectId;
  sourceType: ClinicalNoteSource;
  sourceId?: Types.ObjectId;
  text: string;
  editCount?: number;
  lastEditedAt?: Date;
  lastEditedBy?: unknown;
  authorId?: unknown;
  doctorId?: unknown;
  createdAt: Date;
  updatedAt: Date;
}

export const serializeNote = (n: NoteDoc) => ({
  _id: String(n._id),
  patientId: String(n.patientId),
  sourceType: n.sourceType ?? "patient", // PHASE 7 — a note written before sourceType existed is a patient-file note
  sourceId: n.sourceId ? String(n.sourceId) : undefined,
  text: n.text,
  author: who(n.authorId),
  doctor: who(n.doctorId),
  createdAt: n.createdAt,
  updatedAt: n.updatedAt,
  editCount: n.editCount ?? 0,
  edited: (n.editCount ?? 0) > 0 ? { at: n.lastEditedAt ?? n.updatedAt, by: who(n.lastEditedBy) } : null,
});

const populateNote = <T extends mongoose.Query<unknown, unknown>>(q: T) => q.populate("authorId", "name").populate("doctorId", "name").populate("lastEditedBy", "name");

const loadFresh = async (req: Request, patientId: unknown, noteId: unknown) => {
  const doc = await populateNote(ClinicalNote.findOne({ _id: noteId, clinicId: req.clinicId, patientId }).select("-revisions")).lean<NoteDoc | null>();
  return doc ? serializeNote(doc) : null;
};

// ---------------------------------------------------------------------------------------------------- create
const createSchema = z.object({
  text: z.string().trim().min(1, "Write something first").max(CLINICAL_NOTE_MAX_CHARS),
  sourceType: z.enum(CLINICAL_NOTE_SOURCES).default("patient"),
  sourceId: z.string().length(24).optional(),
  // Generated by the client once per "Add note" dialog: a double click / retry of the SAME dialog is the same note.
  requestId: z.string().regex(/^[A-Za-z0-9_-]{8,64}$/).optional(),
});

/** Does the source record exist for THIS clinic and THIS patient? Returns the extra data the note should carry. */
async function resolveSource(req: Request, patientId: unknown, type: ClinicalNoteSource, sourceId?: string): Promise<{ ok: true; doctorId?: Types.ObjectId } | { ok: false }> {
  if (type === "patient") return sourceId ? { ok: false } : { ok: true };
  if (!sourceId || !mongoose.isValidObjectId(sourceId)) return { ok: false };
  const scope = { _id: sourceId, clinicId: req.clinicId, patientId };
  if (type === "appointment") {
    const a = await Appointment.findOne({ ...scope, type: { $ne: "blocked" } }).select("doctorId").lean();
    return a ? { ok: true, doctorId: a.doctorId } : { ok: false };
  }
  if (type === "dental_treatment") return (await DentalTreatmentItem.exists(scope)) ? { ok: true } : { ok: false };
  return (await DermTreatmentItem.exists(scope)) ? { ok: true } : { ok: false };
}

const DUP_WINDOW_MS = 5000;

export const createNote = asyncHandler(async (req: Request, res: Response) => {
  const patient = await loadNotePatient(req, res);
  if (!patient) return;
  const body = createSchema.parse(req.body);

  const src = await resolveSource(req, patient._id, body.sourceType, body.sourceId);
  if (!src.ok) return res.status(404).json({ message: "The record this note belongs to was not found for this patient" });

  const requestKey = body.requestId ? `${req.clinicId}:${patient._id}:${req.userId}:${body.requestId}` : undefined;
  const replay = async () => {
    const same = requestKey
      ? await ClinicalNote.findOne({ requestKey, clinicId: req.clinicId, patientId: patient._id }).select("_id")
      : // no key (older client): the same author sending the very same text to the same place a moment ago is a double click
        await ClinicalNote.findOne({
          clinicId: req.clinicId, patientId: patient._id, authorId: req.userId, sourceType: body.sourceType,
          ...(body.sourceId ? { sourceId: body.sourceId } : { sourceId: { $exists: false } }),
          text: body.text, createdAt: { $gte: new Date(Date.now() - DUP_WINDOW_MS) },
        }).select("_id");
    return same ? loadFresh(req, patient._id, same._id) : null;
  };

  const prior = await replay();
  if (prior) return res.status(200).json({ note: prior, duplicate: true });

  try {
    const created = await ClinicalNote.create({
      clinicId: req.clinicId, patientId: patient._id, authorId: req.userId,
      ...(src.doctorId ? { doctorId: src.doctorId } : {}),
      sourceType: body.sourceType, ...(body.sourceId ? { sourceId: body.sourceId } : {}),
      text: body.text, ...(requestKey ? { requestKey } : {}),
    });
    return res.status(201).json({ note: await loadFresh(req, patient._id, created._id), duplicate: false });
  } catch (err) {
    if ((err as { code?: number })?.code === 11000) {
      // two identical requests raced: the loser returns the winner's note instead of failing
      const winner = await replay();
      if (winner) return res.status(200).json({ note: winner, duplicate: true });
    }
    throw err;
  }
});

// ---------------------------------------------------------------------------------------------------- edit
const updateSchema = z.object({
  text: z.string().trim().min(1, "Write something first").max(CLINICAL_NOTE_MAX_CHARS),
  // the version the user was looking at; an edit made from stale data is refused instead of overwriting someone else's edit
  expectedEditCount: z.number().int().min(0).optional(),
});

export const updateNote = asyncHandler(async (req: Request, res: Response) => {
  const patient = await loadNotePatient(req, res);
  if (!patient) return;
  const noteId = idParam(req.params.noteId);
  if (!noteId) return res.status(404).json({ message: "Note not found" });
  const body = updateSchema.parse(req.body);

  const cur = await ClinicalNote.findOne({ _id: noteId, clinicId: req.clinicId, patientId: patient._id }).select("text editCount lastEditedAt createdAt").lean();
  if (!cur) return res.status(404).json({ message: "Note not found" });
  const stale = async () => res.status(409).json({ message: "This note was changed by someone else. Review the latest version and try again.", code: "NOTE_CHANGED", note: await loadFresh(req, patient._id, noteId) });

  if (body.expectedEditCount !== undefined && body.expectedEditCount !== (cur.editCount ?? 0)) return stale();
  if (body.text === cur.text) return res.json({ note: await loadFresh(req, patient._id, noteId), unchanged: true }); // nothing to audit
  if ((cur.editCount ?? 0) >= CLINICAL_NOTE_MAX_REVISIONS) return res.status(409).json({ message: "This note has reached its edit limit. Add a new note instead.", code: "NOTE_REVISION_LIMIT" });

  const now = new Date();
  // ONE atomic update: swap the text AND archive the replaced text, only if nobody edited in between.
  const updated = await ClinicalNote.findOneAndUpdate(
    { _id: noteId, clinicId: req.clinicId, patientId: patient._id, ...((cur.editCount ?? 0) === 0 ? { $or: [{ editCount: 0 }, { editCount: { $exists: false } }] } : { editCount: cur.editCount }) }, // PHASE 7 — a legacy note has no editCount field: `editCount: 0` would never match it
    {
      $set: { text: body.text, lastEditedAt: now, lastEditedBy: req.userId },
      $inc: { editCount: 1 },
      $push: { revisions: { text: cur.text, versionAt: cur.lastEditedAt ?? cur.createdAt, editedBy: req.userId, editedAt: now } },
    },
    { new: true, runValidators: true }
  );
  if (!updated) return stale();
  return res.json({ note: await loadFresh(req, patient._id, noteId), unchanged: false });
});

// ---------------------------------------------------------------------------------------------------- read
export const listRevisions = asyncHandler(async (req: Request, res: Response) => {
  const patient = await loadNotePatient(req, res);
  if (!patient) return;
  const noteId = idParam(req.params.noteId);
  if (!noteId) return res.status(404).json({ message: "Note not found" });
  const doc = await ClinicalNote.findOne({ _id: noteId, clinicId: req.clinicId, patientId: patient._id })
    .select("revisions")
    .populate("revisions.editedBy", "name")
    .lean<{ revisions?: { text: string; versionAt: Date; editedBy?: unknown; editedAt: Date }[] } | null>();
  if (!doc) return res.status(404).json({ message: "Note not found" });
  // newest edit first; internal ids are not part of the response
  const revisions = (doc.revisions ?? [])
    .slice()
    .sort((a, b) => new Date(b.editedAt).getTime() - new Date(a.editedAt).getTime())
    .map((r) => ({ text: r.text, versionAt: r.versionAt, editedAt: r.editedAt, editedBy: who(r.editedBy) }));
  return res.json({ revisions });
});

const listQuery = z.object({
  sourceType: z.enum(CLINICAL_NOTE_SOURCES).optional(),
  sourceId: z.string().length(24).optional(),
  limit: z.coerce.number().int().min(1).max(100).optional(),
  before: z.string().max(80).optional(), // "ISO|noteId"
});

export const listNotes = asyncHandler(async (req: Request, res: Response) => {
  const patient = await loadNotePatient(req, res);
  if (!patient) return;
  const q = listQuery.parse(req.query);
  const limit = q.limit ?? 30;
  const filter: Record<string, unknown> = { clinicId: req.clinicId, patientId: patient._id };
  if (q.sourceType) filter.sourceType = q.sourceType;
  if (q.sourceId) filter.sourceId = q.sourceId;
  if (q.before) {
    const cut = q.before.indexOf("|");
    const at = new Date(cut > 0 ? q.before.slice(0, cut) : q.before);
    const id = cut > 0 ? q.before.slice(cut + 1) : "";
    if (Number.isNaN(at.getTime()) || !mongoose.isValidObjectId(id)) return res.status(400).json({ message: "Invalid cursor" });
    filter.$or = [{ createdAt: { $lt: at } }, { createdAt: at, _id: { $lt: id } }];
  }
  const docs = await populateNote(ClinicalNote.find(filter).select("-revisions").sort({ createdAt: -1, _id: -1 }).limit(limit + 1)).lean<NoteDoc[]>();
  const page = docs.slice(0, limit);
  const last = page[page.length - 1];
  return res.json({
    notes: page.map(serializeNote),
    nextCursor: docs.length > limit && last ? `${new Date(last.createdAt).toISOString()}|${last._id}` : null,
  });
});
