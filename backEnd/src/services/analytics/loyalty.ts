import { LoyaltyAccount } from "../../models/LoyaltyAccount";
import { LoyaltyTransaction } from "../../models/LoyaltyTransaction";
import { LoyaltyCheckIn } from "../../models/LoyaltyCheckIn";
import { LoyaltyRedemption } from "../../models/LoyaltyRedemption";
import type { AnalyticsScope } from "./scope";
import type { DateRange, Granularity } from "./range";
import { rollup } from "./range";
import { dayOf } from "./agg";
import { ratePct } from "./metrics";

/**
 * PHASE 6 — LOYALTY METRICS (only for a clinic whose Loyalty add-on is active; the controller enforces that with the existing entitlement).
 * Everything is counted from stored Loyalty records; nothing is derived, estimated or attributed to revenue:
 *   - NO "revenue generated by loyalty" / ROI: there is no causal data link between points and money, so none is shown.
 *   - Loyalty is a CLINIC program (not attributed to a doctor), so it is an owner-only, clinic-wide section.
 *
 *  Enrolled members     = accounts joined up to the end of the range         · Active members = of those, status "active"
 *  New members          = accounts joined in the range (joinedAt)
 *  Points issued        = Σ pointsDelta of earn_visit / earn_spending / manual_credit in the range (ledger createdAt)
 *  Points redeemed      = Σ |pointsDelta| of reward_redemption in the range;  returned = reversals of a redemption (positive delta)
 *  Outstanding points   = Σ pointsBalance of all accounts AS OF NOW (a balance, not a flow)
 *  Redemptions          = redemption requests by requestedAt in the range, display status (confirming→pending, reversing→confirmed)
 *  Check-ins            = check-in requests by requestedAt in the range, by status
 *  Tier distribution    = accounts by CURRENT tier key as of now
 */
type Row = Record<string, any>;
const ISSUE = ["earn_visit", "earn_spending", "manual_credit"];
const shown = (st: string) => (st === "confirming" ? "pending" : st === "reversing" ? "confirmed" : st);

export async function loyaltyStats(s: AnalyticsScope, r: DateRange, g: Granularity) {
  const cid = s.clinicOid;
  const inRange = (f: string) => ({ [f]: { $gte: r.start, $lt: r.end } });

  const [accounts, tiers, balance, newMembers, ledger, ckRows, redRows, ledgerDay, ckDay, newDay] = await Promise.all([
    LoyaltyAccount.aggregate([{ $match: { clinicId: cid, joinedAt: { $lt: r.end } } }, { $group: { _id: "$status", n: { $sum: 1 } } }]),
    LoyaltyAccount.aggregate([{ $match: { clinicId: cid } }, { $group: { _id: "$tier.key", n: { $sum: 1 } } }]),
    LoyaltyAccount.aggregate([{ $match: { clinicId: cid } }, { $group: { _id: null, points: { $sum: "$pointsBalance" }, members: { $sum: 1 } } }]),
    LoyaltyAccount.countDocuments({ clinicId: cid, ...inRange("joinedAt") }),
    LoyaltyTransaction.aggregate([
      { $match: { clinicId: cid, ...inRange("createdAt") } },
      { $group: { _id: { type: "$type", rev: "$metadata.reversedType" }, points: { $sum: "$pointsDelta" }, n: { $sum: 1 } } },
    ]),
    LoyaltyCheckIn.aggregate([{ $match: { clinicId: cid, ...inRange("requestedAt") } }, { $group: { _id: "$status", n: { $sum: 1 } } }]),
    LoyaltyRedemption.aggregate([
      { $match: { clinicId: cid, ...inRange("requestedAt") } },
      { $group: { _id: { reward: "$rewardNameSnapshot", status: "$status" }, n: { $sum: 1 }, points: { $sum: "$pointsCostSnapshot" } } },
    ]),
    LoyaltyTransaction.aggregate([
      { $match: { clinicId: cid, type: { $in: ISSUE }, ...inRange("createdAt") } },
      { $group: { _id: dayOf("$createdAt"), points: { $sum: "$pointsDelta" } } },
    ]),
    LoyaltyCheckIn.aggregate([{ $match: { clinicId: cid, status: "confirmed", ...inRange("requestedAt") } }, { $group: { _id: dayOf("$requestedAt"), n: { $sum: 1 } } }]),
    LoyaltyAccount.aggregate([{ $match: { clinicId: cid, ...inRange("joinedAt") } }, { $group: { _id: dayOf("$joinedAt"), n: { $sum: 1 } } }]),
  ]);

  let enrolled = 0, active = 0;
  for (const a of accounts) { enrolled += a.n ?? 0; if (a._id === "active") active += a.n ?? 0; }

  let issued = 0, redeemed = 0, returned = 0;
  for (const x of ledger as Row[]) {
    const t = x._id?.type;
    if (ISSUE.includes(t)) issued += x.points ?? 0;
    else if (t === "reward_redemption") redeemed += Math.abs(x.points ?? 0);
    else if (t === "reversal" && x._id?.rev === "reward_redemption" && (x.points ?? 0) > 0) returned += x.points ?? 0;
  }

  const ck = { total: 0, confirmed: 0, rejected: 0, expired: 0, cancelled: 0, pending: 0 };
  for (const x of ckRows as Row[]) { ck.total += x.n ?? 0; if (x._id in ck) (ck as any)[x._id] += x.n ?? 0; }
  const resolved = ck.confirmed + ck.rejected + ck.expired;

  const red = { requested: 0, confirmed: 0, rejected: 0, reversed: 0, pending: 0 };
  const per = new Map<string, { name: string; requested: number; confirmed: number; pointsRedeemed: number }>();
  for (const x of redRows as Row[]) {
    const st = shown(String(x._id?.status));
    const name = String(x._id?.reward ?? "—");
    red.requested += x.n ?? 0;
    if (st in red) (red as any)[st] += x.n ?? 0;
    const row = per.get(name) ?? { name, requested: 0, confirmed: 0, pointsRedeemed: 0 };
    row.requested += x.n ?? 0;
    if (st === "confirmed") { row.confirmed += x.n ?? 0; row.pointsRedeemed += x.points ?? 0; }
    per.set(name, row);
  }

  const m = (rows: Row[], f: string) => new Map<string, number>(rows.map((x) => [String(x._id), x[f] ?? 0]));
  const series = (map: Map<string, number>) => rollup(map, r, g);
  const issuedS = series(m(ledgerDay, "points")), ckS = series(m(ckDay, "n")), newS = series(m(newDay, "n"));
  return {
    enrolled,
    activeMembers: active,
    newMembers,
    points: { issued, redeemed, returned, outstanding: balance[0]?.points ?? 0 },
    checkIns: { ...ck, confirmedShareOfResolved: ratePct(ck.confirmed, resolved) },
    redemptions: red,
    topRewards: Array.from(per.values()).sort((a, b) => b.confirmed - a.confirmed || b.requested - a.requested || (a.name < b.name ? -1 : 1)).slice(0, 8),
    tiers: (tiers as Row[]).map((t) => ({ tier: t._id ?? "none", members: t.n ?? 0 })).sort((a, b) => (a.tier < b.tier ? -1 : 1)),
    trend: {
      granularity: g,
      points: issuedS.map((p, i) => ({ key: p.key, pointsIssued: p.value, checkIns: ckS[i]?.value ?? 0, newMembers: newS[i]?.value ?? 0 })),
    },
  };
}
